// ─────────────────────────────────────────────────────────────────────────────
// Visual Script → GDScript compiler
// ─────────────────────────────────────────────────────────────────────────────

export function visualScriptToGDScript(script) {
  if (!script || !script.nodes) {
    return `extends Node\n# Empty script\n`;
  }

  const lines = ['extends Node', '# Auto-compiled from Visual Script: ' + (script.name || 'Script'), ''];
  const vars  = script.variables || [];
  vars.forEach(v => {
    lines.push(`var ${v.name} = ${JSON.stringify(v.defaultValue)}`);
  });
  lines.push('');

  const eventNodes = script.nodes.filter(n => n.type?.startsWith('Event_'));

  eventNodes.forEach(event => {
    const methodMap = {
      Event_OnStart:     '_ready',
      Event_OnUpdate:    '_process(delta)',
      Event_OnCollision: '_on_body_entered(body)',
    };
    const method = methodMap[event.type] || '_ready';
    lines.push(`func ${method}:`);
    lines.push(`  pass  # TODO: connect action nodes`);
    lines.push('');
  });

  return lines.join('\n');
}

// ─────────────────────────────────────────────────────────────────────────────
// Helpers
// ─────────────────────────────────────────────────────────────────────────────

function sanitizeName(name) {
  return (name || 'Node').replace(/[^a-zA-Z0-9_]/g, '_').replace(/^(\d)/, '_$1');
}
