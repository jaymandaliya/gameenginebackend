/**
 * GodotConverter
 *
 * Converts a GameProject (our standard JSON format) into Godot 4 project files:
 *   - project.godot          (engine config)
 *   - scenes/<name>.tscn     (Godot scene text format)
 *   - scripts/<name>.gd      (GDScript from visual script JSON)
 *   - export_presets.cfg     (export config for each platform)
 *
 * Used by BuildWorker to prepare the Godot project before headless export.
 */

import { v4 as uuid } from 'uuid';

// ─────────────────────────────────────────────────────────────────────────────
// project.godot generator
// ─────────────────────────────────────────────────────────────────────────────

export function generateProjectGodot(project) {
  const name = (project.project?.name || 'Game').replace(/[^a-zA-Z0-9 _-]/g, '');
  const entryScene = `res://scenes/${project.scenes?.[0]?.name || 'Main'}.tscn`;
  const godotVersion = process.env.GODOT_VERSION || '4.6.3';
  const majorMinor  = godotVersion.split('.').slice(0, 2).join('.');

  return `; Engine configuration file.
; Generated by gameEngineMobile build pipeline
; Do not edit manually unless you know what you're doing.

config_version=5

[application]
config/name="${name}"
run/main_scene="${entryScene}"
config/features=PackedStringArray("${majorMinor}", "GL Compatibility")
config/icon="res://icon.svg"

[display]
window/size/viewport_width=1080
window/size/viewport_height=1920
window/stretch/mode="canvas_items"
window/stretch/aspect="expand"

[physics]
2d/default_gravity=980

[rendering]
renderer/rendering_method="gl_compatibility"
renderer/rendering_method.mobile="gl_compatibility"
`;
}

// ─────────────────────────────────────────────────────────────────────────────
// .tscn scene file generator
// ─────────────────────────────────────────────────────────────────────────────

export function generateTscn(scene) {
  const entities = scene.entities || [];
  const resources = [];
  const nodes = [];
  let resourceIndex = 1;

  // Collect unique sprite resources
  const spriteResources = new Map();
  entities.forEach(entity => {
    const sprite = entity.components?.sprite;
    if (sprite?.url && !spriteResources.has(sprite.url)) {
      spriteResources.set(sprite.url, resourceIndex++);
    }
  });

  // Resource declarations (external textures)
  spriteResources.forEach((idx, url) => {
    resources.push(`[ext_resource type="Texture2D" path="${url}" id="${idx}_${uuid().slice(0,8)}"]`);
  });

  // Root node
  nodes.push(`[node name="Root" type="Node2D"]`);

  // Camera
  nodes.push(`\n[node name="Camera" type="Camera2D" parent="."]
position = Vector2(540, 960)
zoom = Vector2(1, 1)
`);

  // HUD Canvas Layer
  nodes.push(`\n[node name="HUD" type="CanvasLayer" parent="."]`);

  // Background
  const bgColor = scene.backgroundColor || '#1a1a2e';
  nodes.push(`
[node name="Background" type="ColorRect" parent="."]
z_index = -10
anchors_preset = 15
anchor_right = 1.0
anchor_bottom = 1.0
color = Color("${bgColor.replace('#','')}")
`);

  // Entity nodes
  entities.forEach((entity) => {
    const t       = entity.components?.transform || {};
    const sprite  = entity.components?.sprite    || {};
    const physics = entity.components?.physics   || {};
    const nodeName = sanitizeName(entity.name || entity.id);

    const posX = (t.x || 0) + (sprite.width  || 48) / 2;
    const posY = (t.y || 0) + (sprite.height || 48) / 2;

    const isStatic  = physics.bodyType === 'static';
    const isDynamic = physics.bodyType === 'dynamic';

    if (isDynamic) {
      // CharacterBody2D for players/enemies (movement-controlled)
      const scriptName = entity.type === 'player' ? 'PlayerController' : 'EnemyController';
      nodes.push(`
[node name="${nodeName}" type="CharacterBody2D" parent="."]
position = Vector2(${posX.toFixed(1)}, ${posY.toFixed(1)})
`);
      // Sprite
      const resId = sprite.url ? spriteResources.get(sprite.url) : null;
      if (resId) {
        nodes.push(`
[node name="Sprite" type="Sprite2D" parent="${nodeName}"]
texture = ExtResource("${resId}_...")
`);
      } else {
        nodes.push(`
[node name="Sprite" type="ColorRect" parent="${nodeName}"]
offset_left = ${-(sprite.width || 48) / 2}
offset_top = ${-(sprite.height || 48) / 2}
offset_right = ${(sprite.width  || 48) / 2}
offset_bottom = ${(sprite.height || 48) / 2}
color = Color("${(sprite.color || '#4a9eff').replace('#','')}ff")
`);
      }

      // Collider
      nodes.push(`
[node name="Collider" type="CollisionShape2D" parent="${nodeName}"]
shape = RectangleShape2D(${(sprite.width || 48).toFixed(0)}, ${(sprite.height || 48).toFixed(0)})
`);

    } else if (isStatic) {
      // StaticBody2D for platforms / walls
      nodes.push(`
[node name="${nodeName}" type="StaticBody2D" parent="."]
position = Vector2(${posX.toFixed(1)}, ${posY.toFixed(1)})

[node name="Shape" type="CollisionShape2D" parent="${nodeName}"]
shape = RectangleShape2D(${(sprite.width || 48).toFixed(0)}, ${(sprite.height || 48).toFixed(0)})

[node name="Visual" type="ColorRect" parent="${nodeName}"]
offset_left = ${-(sprite.width || 48) / 2}
offset_top = ${-(sprite.height || 48) / 2}
offset_right = ${(sprite.width  || 48) / 2}
offset_bottom = ${(sprite.height || 48) / 2}
color = Color("${(sprite.color || '#4a4a4a').replace('#','')}ff")
`);

    } else {
      // Area2D for collectibles / triggers
      nodes.push(`
[node name="${nodeName}" type="Area2D" parent="."]
position = Vector2(${posX.toFixed(1)}, ${posY.toFixed(1)})

[node name="Shape" type="CollisionShape2D" parent="${nodeName}"]
shape = CircleShape2D(${Math.min(sprite.width || 24, sprite.height || 24) / 2})

[node name="Visual" type="Label" parent="${nodeName}"]
text = "${sprite.icon || '📦'}"
position = Vector2(-12, -12)
`);
    }
  });

  const header = `[gd_scene load_steps=${resources.length + 2} format=3 uid="uid://${uuid().slice(0,12)}"]`;
  return [header, ...resources, '\n', ...nodes].join('\n');
}

