export function generatePlayerScript(entity) {
  const physics = entity.components?.physics || {};
  const speed   = physics.moveSpeed || 300;

  return `extends CharacterBody2D
# Auto-generated by gameEngineMobile

const SPEED = ${speed}.0
const JUMP_VELOCITY = -400.0
var lives = 3
var score = 0

func _physics_process(delta):
  # Gravity
  if not is_on_floor():
    velocity += get_gravity() * delta

  # Touch / keyboard input
  var direction = Input.get_axis("ui_left", "ui_right")
  if direction:
    velocity.x = direction * SPEED
  else:
    velocity.x = move_toward(velocity.x, 0, SPEED)

  if Input.is_action_just_pressed("ui_accept") and is_on_floor():
    velocity.y = JUMP_VELOCITY

  move_and_slide()

func collect(points):
  score += points
  get_node("/root/HUD").update_score(score)

func take_damage():
  lives -= 1
  get_node("/root/HUD").update_lives(lives)
  if lives <= 0:
    get_tree().change_scene_to_file("res://scenes/GameOver.tscn")
`;
}

export function generateEnemyScript(entity) {
  const physics     = entity.components?.physics || {};
  const speed       = physics.moveSpeed     || 80;
  const pattern     = physics.movePattern   || 'patrol';
  const direction   = physics.moveDirection || 'right';

  return `extends CharacterBody2D
# Auto-generated by gameEngineMobile

const SPEED = ${speed}.0
var direction = ${direction === 'left' ? -1 : 1}
var _time = 0.0

func _physics_process(delta):
  _time += delta
  if not is_on_floor():
    velocity += get_gravity() * delta

  match "${pattern}":
    "patrol":
      velocity.x = SPEED * direction
      if is_on_wall(): direction *= -1
    "sine":
      velocity.x = sin(_time * 2.0) * SPEED
    "chase":
      var player = get_node_or_null("/root/Root/Player")
      if player:
        var diff = player.global_position - global_position
        velocity = diff.normalized() * SPEED

  move_and_slide()
`;
}

export function generateCollectibleScript(entity) {
  const points = entity.components?.script?.variables?.points || 10;
  return `extends Area2D
# Auto-generated by gameEngineMobile

var points = ${points}

func _ready():
  connect("body_entered", _on_body_entered)

func _on_body_entered(body):
  if body.is_in_group("player"):
    body.collect(points)
    queue_free()
`;
}

